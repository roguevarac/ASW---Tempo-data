CREATE OR REPLACE FUNCTION public.fn_audit_trigger()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
declare
    v_operation audit_operation_enum;
begin
    if tg_op = 'INSERT' then
        insert into audit_logs(table_name, row_id, operation, old_data, new_data)
        values (tg_table_name, new.id, 'INSERT', null, to_jsonb(new));
        return new;
    elsif tg_op = 'UPDATE' then
        -- Si lo único que cambió es updated_at, no hay nada que auditar.
        if (to_jsonb(old) - 'updated_at') = (to_jsonb(new) - 'updated_at') then
            return new;
        end if;
        v_operation := case when new.deleted_at is not null and old.deleted_at is null then 'SOFT_DELETE' else 'UPDATE' end;
        insert into audit_logs(table_name, row_id, operation, old_data, new_data)
        values (tg_table_name, new.id, v_operation, to_jsonb(old), to_jsonb(new));
        return new;
    elsif tg_op = 'DELETE' then
        insert into audit_logs(table_name, row_id, operation, old_data, new_data)
        values (tg_table_name, old.id, 'HARD_DELETE', to_jsonb(old), null);
        return old;
    end if;
    return null;
end;
$function$
;
CREATE OR REPLACE FUNCTION public.fn_carga_historica_tempo_batch(p_rows jsonb)
 RETURNS TABLE(idx integer, estado text, detalle text)
 LANGUAGE plpgsql
AS $function$
declare
    r          jsonb;
    i          integer := 0;
    v_in       text;
    v_tempo    text;
    v_pos      integer;
    v_rpos     integer;
    v_track    text;
    v_artist   text;
    v_id       uuid;
    v_actual   text;
    v_new_num  boolean;
    v_act_num  boolean;
begin
    for r in select * from jsonb_array_elements(p_rows) loop
        i := i + 1;
        begin
            v_in    := regexp_replace(trim(coalesce(r->>'track_artist', '')), '\s+', ' ', 'g');
            v_tempo := nullif(trim(coalesce(r->>'tempo_id', '')), '');

            -- Numéricos sin ceros de relleno; "0" cuenta como vacío.
            if v_tempo ~ '^[0-9]+$' then
                v_tempo := nullif(ltrim(v_tempo, '0'), '');
            end if;

            if v_in = '' then
                idx := i; estado := 'ERROR'; detalle := 'Fila sin título';
                return next; continue;
            end if;
            if v_tempo is null then
                idx := i; estado := 'IGNORADA'; detalle := 'Tempo ID vacío o 0';
                return next; continue;
            end if;

            -- 1) Obra y artista por el último " - ", normalizados.
            v_id := null; v_actual := null;
            v_rpos := position(' - ' in reverse(v_in));
            if v_rpos > 0 then
                v_pos    := length(v_in) - v_rpos - 1;
                v_track  := substring(v_in from 1 for v_pos - 1);
                v_artist := substring(v_in from v_pos + 3);

                select tm.id, tm.tempo_id into v_id, v_actual
                from tracks_master tm
                where tm.deleted_at is null
                  and lower(tm.track_name_clean)  = lower(fn_normalize_text(v_track))
                  and lower(tm.artist_name_clean) = lower(fn_normalize_text(v_artist))
                limit 1;
            end if;

            -- 2) Respaldo: texto completo tal cual.
            if v_id is null then
                select tm.id, tm.tempo_id into v_id, v_actual
                from tracks_master tm
                where tm.deleted_at is null
                  and lower(tm.track_artist_concat) = lower(v_in)
                limit 1;
            end if;

            if v_id is null then
                idx := i; estado := 'NO ENCONTRADA'; detalle := 'No existe en la tabla principal';
                return next; continue;
            end if;

            v_new_num := v_tempo ~ '^[0-9]+$';
            v_act_num := coalesce(v_actual ~ '^[0-9]+$', false);

            if v_actual is not null and fn_norm_tempo_id(v_actual) = fn_norm_tempo_id(v_tempo) then
                idx := i; estado := 'SIN CAMBIOS'; detalle := 'Ya tenía ese tempo_id';

            elsif v_act_num and v_new_num then
                idx := i; estado := 'CONFLICTO';
                detalle := 'Ya tiene ' || v_actual || '; el archivo trae ' || v_tempo || ' (no se pisó)';

            elsif v_act_num and not v_new_num then
                idx := i; estado := 'SIN CAMBIOS';
                detalle := 'Ya tiene el número ' || v_actual || '; se ignora el marcador ' || v_tempo;

            else
                update tracks_master
                set tempo_id  = v_tempo,
                    estado_bo = case when v_new_num then 'ok'::estado_bo_enum else estado_bo end
                where id = v_id;

                if v_new_num then
                    perform fn_merge_tempo_duplicates(v_tempo);
                end if;

                idx := i; estado := 'ACTUALIZADA';
                detalle := 'Antes: ' || coalesce(v_actual, 'vacío');
            end if;
            return next;

        exception when others then
            idx := i; estado := 'ERROR'; detalle := sqlerrm;
            return next;
        end;
    end loop;
end;
$function$
;
