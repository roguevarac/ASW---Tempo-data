    select tm.id, tm.tempo_id into v_master_id, v_tempo_id
    from tracks_master tm
    where fn_norm_tempo_id(tm.tempo_id) = fn_norm_tempo_id(p_tempo_id)
      and tm.deleted_at is null
    limit 1;

    if v_master_id is null then
