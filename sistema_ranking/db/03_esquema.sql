CREATE OR REPLACE FUNCTION public.fn_upsert_master_tempo_batch(p_rows jsonb)
 RETURNS TABLE(idx integer, error_message text)
 LANGUAGE plpgsql
AS $function$
declare
    r jsonb;
    i integer := 0;
    v_count integer;
    v_clean text;
begin
    for r in select * from jsonb_array_elements(p_rows) loop
        i := i + 1;
        begin
            v_clean := nullif(trim(r->>'tempo_id'), '');

            update tracks_master
            set tempo_id = v_clean,
                estado_bo = case when v_clean is not null then 'ok'::estado_bo_enum else estado_bo end
            where lower(track_artist_concat) = lower(trim(r->>'track_artist'))
              and deleted_at is null;

            get diagnostics v_count = row_count;

            if v_count = 0 then
                idx := i;
                error_message := 'No se encontró la obra "' || (r->>'track_artist') || '" en la tabla principal.';
            else
                perform fn_merge_tempo_duplicates(v_clean);
                idx := i; error_message := null;
            end if;
            return next;
        exception when others then
            idx := i; error_message := sqlerrm;
            return next;
        end;
    end loop;
end;
$function$
;
