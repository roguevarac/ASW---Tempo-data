CREATE OR REPLACE FUNCTION public.trg_tracks_master_flag_duplicate()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$
begin
    if exists (
        select 1 from tracks_master
        where lower(track_name_clean) = lower(new.track_name_clean)
          and lower(artist_name_clean) = lower(new.artist_name_clean)
          and deleted_at is null
          and id <> new.id
    ) then
        new.estado_bo := 'duplicada';
    end if;
    return new;
end;
$function$
;
CREATE OR REPLACE FUNCTION public.trg_tracks_master_normalize()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$
begin
    new.track_name_clean    := fn_normalize_text(new.track_name_raw);
    new.artist_name_clean   := fn_normalize_text(new.artist_name_raw);
    new.track_artist_concat := new.track_name_clean || ' - ' || new.artist_name_clean;
    new.updated_at          := now();
    return new;
end;
$function$
;

