CREATE OR REPLACE FUNCTION public.fn_procesar_tempo_historico(p_limite integer DEFAULT 5000)
 RETURNS TABLE(estado text, filas bigint, pendientes bigint)
 LANGUAGE plpgsql
AS $function$
declare
    v_filas bigint[];
    v_arr   jsonb;
begin
    -- Próximo lote sin procesar, en orden de fila (sin tablas temporales).
    select array_agg(x.fila order by x.fila),
           jsonb_agg(jsonb_build_object('track_artist', x.concatenate, 'tempo_id', x.tempo_id) order by x.fila)
      into v_filas, v_arr
    from (
        select s.fila, s.concatenate, s.tempo_id
        from staging_tempo_historico s
        where not s.procesado
        order by s.fila
        limit p_limite
    ) x;

    if v_arr is null then
        return;   -- no queda nada pendiente
    end if;

    -- idx (1, 2, 3...) es la posición en el lote; v_filas[idx] es la fila original.
    insert into resultado_tempo_historico (fila, concatenate, tempo_id, estado, detalle)
    select s.fila, s.concatenate, s.tempo_id, b.estado, b.detalle
    from fn_carga_historica_tempo_batch(v_arr) b
    join staging_tempo_historico s on s.fila = v_filas[b.idx]
    on conflict (fila) do update
        set estado = excluded.estado, detalle = excluded.detalle, procesado_at = now();

    update staging_tempo_historico
    set procesado = true
    where fila = any(v_filas);

    return query
    select r.estado, count(*)::bigint,
           (select count(*) from staging_tempo_historico st where not st.procesado)::bigint
    from resultado_tempo_historico r
    where r.fila = any(v_filas)
    group by r.estado
    order by 2 desc;
end;
$function$
;
CREATE OR REPLACE FUNCTION public.fn_safe_bigint(v text)
 RETURNS bigint
 LANGUAGE plpgsql
 IMMUTABLE
AS $function$
begin
    if v is null or trim(lower(v)) in ('', 'n/a', 'na', '-', 'null') then return null; end if;
    return v::bigint;
exception when others then return null;
end;
