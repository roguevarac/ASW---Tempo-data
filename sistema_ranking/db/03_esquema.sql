CREATE OR REPLACE FUNCTION public.fn_master_export(p_date_from date DEFAULT NULL::date, p_date_to date DEFAULT NULL::date, p_pais pais_code_enum DEFAULT NULL::pais_code_enum)
 RETURNS TABLE(track_artist_concat text, tempo_id text)
 LANGUAGE plpgsql
 STABLE
AS $function$
#variable_conflict use_column
begin
    return query
    select tm.track_artist_concat, tm.tempo_id
    from tracks_master tm
    left join territory_tracks tt
        on tt.track_master_id = tm.id
       and tt.deleted_at is null
       and (p_pais      is null or tt.pais_code = p_pais)
       and (p_date_from is null or tt.snapshot_date >= p_date_from)
       and (p_date_to   is null or tt.snapshot_date <= p_date_to)
    where tm.deleted_at is null
      and (
        (p_pais is null and p_date_from is null and p_date_to is null)
        or tt.id is not null
      )
    group by tm.track_artist_concat, tm.tempo_id
    order by tm.track_artist_concat;
end;
$function$
;
CREATE OR REPLACE FUNCTION public.fn_master_view(p_date_from date DEFAULT NULL::date, p_date_to date DEFAULT NULL::date, p_pais pais_code_enum DEFAULT NULL::pais_code_enum, p_include_deleted boolean DEFAULT false)
 RETURNS TABLE(id uuid, track_artist_concat text, track_name_clean text, tempo_id text, last_chart_date date, deleted_at timestamp with time zone)
 LANGUAGE plpgsql
 STABLE
AS $function$
#variable_conflict use_column
begin
    return query
    select tm.id, tm.track_artist_concat, tm.track_name_clean, tm.tempo_id,
           max(tt.snapshot_date) as last_chart_date, tm.deleted_at
    from tracks_master tm
    left join territory_tracks tt
        on tt.track_master_id = tm.id
       and tt.deleted_at is null
       and (p_pais      is null or tt.pais_code = p_pais)
       and (p_date_from is null or tt.snapshot_date >= p_date_from)
       and (p_date_to   is null or tt.snapshot_date <= p_date_to)
    where (p_include_deleted or tm.deleted_at is null)
      and (
        (p_pais is null and p_date_from is null and p_date_to is null)
        or tt.id is not null
      )
    group by tm.id, tm.track_artist_concat, tm.track_name_clean, tm.tempo_id, tm.deleted_at
    order by max(tt.snapshot_date) desc nulls last, tm.track_artist_concat;
end;
$function$
;
CREATE OR REPLACE FUNCTION public.fn_merge_tempo_duplicates(p_tempo_id text)
 RETURNS integer
 LANGUAGE plpgsql
AS $function$
declare
    v_survivor uuid;
    v_merged integer := 0;
begin
    -- Solo IDs numéricos: los marcadores con palabras se repiten a propósito.
    if p_tempo_id is null or p_tempo_id !~ '^[0-9]+$' then
        return 0;
    end if;

    select id into v_survivor
    from tracks_master
    where tempo_id = p_tempo_id and deleted_at is null
    order by created_at asc
    limit 1;

    if v_survivor is null then
        return 0;
    end if;

    select count(*) into v_merged
    from tracks_master
    where tempo_id = p_tempo_id and deleted_at is null and id <> v_survivor;

    if v_merged = 0 then
        return 0;
    end if;

    perform set_config('app.allow_hard_delete', 'true', true);

    -- territory_tracks: si el sobreviviente ya tiene esa combinación, se
    -- descarta la del duplicado; si no, se le reasigna.
    delete from territory_tracks tt
    where tt.track_master_id in (
            select id from tracks_master
            where tempo_id = p_tempo_id and deleted_at is null and id <> v_survivor)
      and exists (
            select 1 from territory_tracks s
            where s.track_master_id = v_survivor
              and s.pais_code = tt.pais_code
              and s.snapshot_date = tt.snapshot_date
              and s.platform = tt.platform);

    update territory_tracks
    set track_master_id = v_survivor, tempo_id = p_tempo_id
    where track_master_id in (
            select id from tracks_master
            where tempo_id = p_tempo_id and deleted_at is null and id <> v_survivor);

    -- territory_bo_report
    delete from territory_bo_report tb
    where tb.track_master_id in (
            select id from tracks_master
            where tempo_id = p_tempo_id and deleted_at is null and id <> v_survivor)
      and exists (
            select 1 from territory_bo_report s
            where s.track_master_id = v_survivor and s.pais_code = tb.pais_code);

    update territory_bo_report
    set track_master_id = v_survivor
    where track_master_id in (
            select id from tracks_master
            where tempo_id = p_tempo_id and deleted_at is null and id <> v_survivor);

    -- territory_tempo_report
    delete from territory_tempo_report tr
    where tr.track_master_id in (
            select id from tracks_master
            where tempo_id = p_tempo_id and deleted_at is null and id <> v_survivor)
      and exists (
            select 1 from territory_tempo_report s
            where s.track_master_id = v_survivor and s.pais_code = tr.pais_code);

    update territory_tempo_report
    set track_master_id = v_survivor
    where track_master_id in (
            select id from tracks_master
            where tempo_id = p_tempo_id and deleted_at is null and id <> v_survivor);

    delete from tracks_master
    where tempo_id = p_tempo_id and deleted_at is null and id <> v_survivor;

    update tracks_master set estado_bo = 'ok'
    where id = v_survivor and estado_bo = 'duplicada';

    return v_merged;
end;
$function$
;
