CREATE OR REPLACE FUNCTION public.fn_territory_export(p_date_from date DEFAULT NULL::date, p_date_to date DEFAULT NULL::date, p_pais pais_code_enum DEFAULT NULL::pais_code_enum)
 RETURNS TABLE("Pais" text, "Track - Artista" text, "Created date" text, "Tempo ID" text, "BO" text, "C/A" text, "% Perf Tempo" text, "% Mech Tempo" text, "Estado" text, "Reclamos" text, "% Mech BO" text, "Estado de trabajo" text)
 LANGUAGE sql
 STABLE
AS $function$
    select
        v.pais_code::text,
        v.track_artist_concat,
        coalesce(v.created_date::text, ''),
        coalesce(v.tempo_id, ''),
        coalesce(v.bo, ''),
        coalesce(v.ca, ''),
        case when v.perf_raw ~ '^[0-9.]+$' then v.perf_raw || '%' else coalesce(v.perf_raw, '') end,
        case when v.mech_raw ~ '^[0-9.]+$' then v.mech_raw || '%' else coalesce(v.mech_raw, '') end,
        coalesce(v.estado, ''),
        coalesce(v.reclamos, ''),
        coalesce(v.mech_bo::text || '%', ''),
        coalesce(v.estado_trabajo, '')
    from fn_territory_view(p_date_from, p_date_to, p_pais, false) v
    order by v.pais_code, v.track_artist_concat;
$function$
;
CREATE OR REPLACE FUNCTION public.fn_territory_view(p_date_from date DEFAULT NULL::date, p_date_to date DEFAULT NULL::date, p_pais pais_code_enum DEFAULT NULL::pais_code_enum, p_include_deleted boolean DEFAULT false)
 RETURNS TABLE(id uuid, track_master_id uuid, pais_code pais_code_enum, tempo_id text, track_artist_concat text, snapshot_date date, created_date date, bo_report_id uuid, bo text, ca text, perf_raw text, mech_raw text, estado text, reclamos text, mech_bo numeric, estado_trabajo text, estado_obra text, deleted_at timestamp with time zone)
 LANGUAGE plpgsql
 STABLE
AS $function$
#variable_conflict use_column
begin
    return query
    select distinct on (tt.track_master_id, tt.pais_code)
        tt.id, tt.track_master_id, tt.pais_code, tm.tempo_id, tm.track_artist_concat,
        tt.snapshot_date, tr.created_date,
        br.id, br.bo_id, br.ca,
        coalesce(tr.perf_raw, tr.perf_pc::text),
        coalesce(tr.mech_raw, tr.mech_pc::text),
        br.bo_status, br.reclamos, br.mech_bo,
        br.estado_trabajo, tr.estado_obra, tt.deleted_at
    from territory_tracks tt
    join tracks_master tm on tm.id = tt.track_master_id
    left join territory_bo_report br
        on br.track_master_id = tt.track_master_id and br.pais_code = tt.pais_code
    left join territory_tempo_report tr
        on tr.track_master_id = tt.track_master_id and tr.pais_code = tt.pais_code
       and tr.deleted_at is null
    where (p_include_deleted or (tt.deleted_at is null and tm.deleted_at is null))
      and (p_date_from is null or tt.snapshot_date >= p_date_from)
      and (p_date_to   is null or tt.snapshot_date <= p_date_to)
      and (p_pais      is null or tt.pais_code = p_pais)
    order by tt.track_master_id, tt.pais_code, tt.snapshot_date desc;
end;
$function$
;
