CREATE OR REPLACE FUNCTION public.fn_upsert_territory_track(p_tempo_id text, p_pais_code pais_code_enum, p_percent_ctrl numeric, p_collect_mec numeric, p_collect_ejec numeric, p_society_id text)
 RETURNS uuid
 LANGUAGE plpgsql
AS $function$
DECLARE
    v_master_id UUID;
    v_row_id    UUID;
BEGIN
    SELECT id INTO v_master_id FROM tracks_master
    WHERE tempo_id = p_tempo_id AND deleted_at IS NULL;

    IF v_master_id IS NULL THEN
