CREATE OR REPLACE FUNCTION public.fn_norm_tempo_id(v text)
 RETURNS text
 LANGUAGE sql
 IMMUTABLE
AS $function$
    -- Para valores numéricos saca los ceros de relleno; para marcadores
    -- con palabras ("NOP", "PENDIENTE") devuelve el texto tal cual.
    select case
        when v is null then null
        when trim(v) ~ '^[0-9]+$' then ltrim(trim(v), '0')
        else upper(trim(v))
    end;
$function$
;
CREATE OR REPLACE FUNCTION public.fn_normalize_text(p_input text)
 RETURNS text
 LANGUAGE plpgsql
 IMMUTABLE
AS $function$
declare
    v_text text;
begin
    if p_input is null then
        return null;
    end if;

    -- Proteger "¿" y "¡" de unaccent (los convierte en "?" y "!").
    v_text := replace(p_input, '¿', chr(1));
    v_text := replace(v_text,  '¡', chr(2));

    v_text := unaccent(v_text);

    v_text := regexp_replace(v_text, '\s*&\s*', ', ', 'g');

    -- (En vivo) / [Live Session] / (Grabado en vivo) ...
    v_text := regexp_replace(v_text, '\s*[\(\[][^\)\]]*\y(en\s+vivo|vivo|live)\y[^\)\]]*[\)\]]\s*', ' ', 'gi');

    -- Segmento entre guiones que arranca con en vivo/live, con o sin
    -- texto extra: "A - En Vivo Gran Rex - B" -> "A - B"
    v_text := regexp_replace(v_text, '\s*-\s*(en\s+vivo|vivo|live)\y[^-]*\s*-\s*', ' - ', 'gi');

    -- Lo mismo al final del título: "A - En Vivo en la Plaza..." -> "A"
    v_text := regexp_replace(v_text, '\s*-\s*(en\s+vivo|vivo|live)\y[^-]*$', '', 'gi');

    v_text := regexp_replace(v_text, '\s+', ' ', 'g');
    v_text := trim(v_text);

    v_text := replace(v_text, chr(1), '¿');
    v_text := replace(v_text, chr(2), '¡');

    return v_text;
end;
$function$
;
CREATE OR REPLACE FUNCTION public.fn_obra_history(p_track_master_id uuid, p_pais pais_code_enum)
 RETURNS TABLE(changed_at timestamp with time zone, changed_by text, bo text, ca text, estado text, reclamos text, mech_bo text, estado_trabajo text, perf_tempo text, mech_tempo text, estado_obra text, created_date text)
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
#variable_conflict use_column
begin
    return query
    with ids as (
        select id, 'territory_bo_report' as t
        from territory_bo_report
        where track_master_id = p_track_master_id and pais_code = p_pais
        union all
        select id, 'territory_tempo_report'
        from territory_tempo_report
        where track_master_id = p_track_master_id and pais_code = p_pais
    ),
    eventos as (
        select al.changed_at as ts, al.changed_by as usuario, al.table_name as tabla, al.new_data as datos
        from audit_logs al
        join ids on al.row_id = ids.id and al.table_name = ids.t
        where al.new_data is not null
    ),
    momentos as (
        select distinct on (date_trunc('minute', e.ts))
               e.ts, e.usuario
        from eventos e
        order by date_trunc('minute', e.ts), e.ts desc
    ),
    fotos as (
        select
            m.ts,
            m.usuario,
            case when (bs.datos ->> 'bo_id') ~ '^[0-9]+$'
                 then ltrim(bs.datos ->> 'bo_id', '0')
                 else bs.datos ->> 'bo_id' end  as f_bo,
            bs.datos ->> 'ca'                   as f_ca,
            bs.datos ->> 'bo_status'            as f_estado,
            bs.datos ->> 'reclamos'             as f_reclamos,
            bs.datos ->> 'mech_bo'              as f_mech_bo,
            bs.datos ->> 'estado_trabajo'       as f_trabajo,
            ts2.datos ->> 'perf_pc'             as f_perf,
            ts2.datos ->> 'mech_pc'             as f_mech,
            ts2.datos ->> 'estado_obra'         as f_obra,
            ts2.datos ->> 'created_date'        as f_created
        from momentos m
        left join lateral (
            select e2.datos from eventos e2
            where e2.tabla = 'territory_bo_report' and e2.ts <= m.ts
            order by e2.ts desc limit 1
        ) bs on true
        left join lateral (
            select e3.datos from eventos e3
            where e3.tabla = 'territory_tempo_report' and e3.ts <= m.ts
            order by e3.ts desc limit 1
        ) ts2 on true
    ),
    con_huella as (
        select f.*,
               concat_ws('|',
                   coalesce(f.f_bo,''), coalesce(f.f_ca,''), coalesce(f.f_estado,''),
                   coalesce(f.f_reclamos,''), coalesce(f.f_mech_bo,''), coalesce(f.f_trabajo,''),
                   coalesce(f.f_perf,''), coalesce(f.f_mech,''), coalesce(f.f_obra,''),
                   coalesce(f.f_created,'')) as huella
        from fotos f
    ),
    con_anterior as (
        select h.*, lag(h.huella) over (order by h.ts) as huella_anterior
        from con_huella h
    )
    select a.ts, a.usuario, a.f_bo, a.f_ca, a.f_estado, a.f_reclamos, a.f_mech_bo,
           a.f_trabajo, a.f_perf, a.f_mech, a.f_obra, a.f_created
    from con_anterior a
    -- Solo si cambió algo respecto de la foto anterior.
    where a.huella_anterior is null or a.huella_anterior <> a.huella
    order by a.ts desc;
end;
$function$
;
