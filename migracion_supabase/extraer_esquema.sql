-- =====================================================================
-- EXTRAER LA ESTRUCTURA COMPLETA DE LA BASE (para pegar en el SQL Editor de Supabase)
--
-- Devuelve UN solo resultado: una fila por objeto, con su definición en SQL.
-- No lee datos de las tablas, solo la estructura. Exportar el resultado a CSV
-- (botón "Download CSV" / "Export") y pasarlo.
--
-- Esquemas incluidos: los del usuario (public y otros creados por ustedes).
-- Se excluyen los internos de Postgres y de Supabase, salvo las referencias que
-- las tablas propias hagan a auth.users (aparecen en las claves foráneas).
-- Además trae lo que usan de Supabase y hay que reemplazar: buckets de storage y
-- sus políticas, cantidad de archivos por bucket, proveedores de login usados y
-- tablas publicadas en realtime. No trae contraseñas, tokens ni contenido de
-- archivos. Las Edge Functions no están en la base: se bajan con
-- descargar_edge_functions.ps1.
-- =====================================================================
WITH esquemas AS (
    SELECT n.oid, n.nspname
    FROM pg_namespace n
    WHERE n.nspname NOT IN ('pg_catalog', 'information_schema', 'pg_toast', 'auth', 'storage', 'realtime',
                            'supabase_functions', 'supabase_migrations', 'extensions', 'graphql', 'graphql_public',
                            'pgbouncer', 'pgsodium', 'pgsodium_masks', 'vault', 'net', 'cron', '_realtime', '_analytics')
      AND n.nspname NOT LIKE 'pg_temp%' AND n.nspname NOT LIKE 'pg_toast_temp%'
)
-- 1. Extensiones instaladas
SELECT 1 AS orden, 'extension' AS tipo, e.extname AS objeto,
       'CREATE EXTENSION IF NOT EXISTS "' || e.extname || '"; -- version ' || e.extversion AS definicion
FROM pg_extension e
UNION ALL
-- 2. Tipos enumerados
SELECT 2, 'enum', s.nspname || '.' || t.typname,
       'CREATE TYPE ' || s.nspname || '.' || t.typname || ' AS ENUM (' ||
       (SELECT string_agg(quote_literal(en.enumlabel), ', ' ORDER BY en.enumsortorder) FROM pg_enum en WHERE en.enumtypid = t.oid) || ');'
FROM pg_type t JOIN esquemas s ON s.oid = t.typnamespace
WHERE t.typtype = 'e'
UNION ALL
-- 3. Tablas con sus columnas
SELECT 3, CASE c.relkind WHEN 'r' THEN 'tabla' WHEN 'p' THEN 'tabla particionada' END, s.nspname || '.' || c.relname,
       'CREATE TABLE ' || s.nspname || '.' || c.relname || ' (' || chr(10) ||
       (SELECT string_agg('    ' || quote_ident(a.attname) || ' ' || format_type(a.atttypid, a.atttypmod)
                          || CASE WHEN a.attidentity = 'a' THEN ' GENERATED ALWAYS AS IDENTITY'
                                  WHEN a.attidentity = 'd' THEN ' GENERATED BY DEFAULT AS IDENTITY' ELSE '' END
                          || CASE WHEN a.attgenerated = 's' THEN ' GENERATED ALWAYS AS (' || pg_get_expr(d.adbin, d.adrelid) || ') STORED'
                                  WHEN d.adbin IS NOT NULL THEN ' DEFAULT ' || pg_get_expr(d.adbin, d.adrelid) ELSE '' END
                          || CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE '' END,
                          ',' || chr(10) ORDER BY a.attnum)
          FROM pg_attribute a
          LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
          WHERE a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped)
       || chr(10) || ');'
       || COALESCE(chr(10) || '-- ' || obj_description(c.oid, 'pg_class'), '')
FROM pg_class c JOIN esquemas s ON s.oid = c.relnamespace
WHERE c.relkind IN ('r', 'p')
UNION ALL
-- 4. Claves primarias, únicas, checks y foráneas
SELECT 4, 'restriccion ' || CASE co.contype WHEN 'p' THEN 'PK' WHEN 'u' THEN 'UNIQUE' WHEN 'c' THEN 'CHECK' WHEN 'f' THEN 'FK' WHEN 'x' THEN 'EXCLUDE' END,
       s.nspname || '.' || c.relname || '.' || co.conname,
       'ALTER TABLE ' || s.nspname || '.' || c.relname || ' ADD CONSTRAINT ' || quote_ident(co.conname) || ' ' || pg_get_constraintdef(co.oid) || ';'
FROM pg_constraint co JOIN pg_class c ON c.oid = co.conrelid JOIN esquemas s ON s.oid = c.relnamespace
UNION ALL
-- 5. Índices que no vienen de una restricción
SELECT 5, 'indice', s.nspname || '.' || i.relname, pg_get_indexdef(i.oid) || ';'
FROM pg_index x JOIN pg_class i ON i.oid = x.indexrelid JOIN pg_class c ON c.oid = x.indrelid JOIN esquemas s ON s.oid = c.relnamespace
WHERE NOT EXISTS (SELECT 1 FROM pg_constraint co WHERE co.conindid = i.oid)
UNION ALL
-- 6. Vistas y vistas materializadas
SELECT 6, CASE c.relkind WHEN 'v' THEN 'vista' ELSE 'vista materializada' END, s.nspname || '.' || c.relname,
       'CREATE ' || CASE c.relkind WHEN 'v' THEN 'VIEW ' ELSE 'MATERIALIZED VIEW ' END || s.nspname || '.' || c.relname
       || ' AS' || chr(10) || pg_get_viewdef(c.oid, true)
FROM pg_class c JOIN esquemas s ON s.oid = c.relnamespace
WHERE c.relkind IN ('v', 'm')
UNION ALL
-- 7. Funciones y procedimientos
SELECT 7, CASE p.prokind WHEN 'p' THEN 'procedimiento' ELSE 'funcion' END, s.nspname || '.' || p.proname,
       pg_get_functiondef(p.oid) || ';'
FROM pg_proc p JOIN esquemas s ON s.oid = p.pronamespace
WHERE p.prokind IN ('f', 'p')
  AND NOT EXISTS (SELECT 1 FROM pg_depend dep WHERE dep.objid = p.oid AND dep.deptype = 'e')  -- excluye funciones de extensiones
UNION ALL
-- 8. Triggers
SELECT 8, 'trigger', s.nspname || '.' || c.relname || '.' || t.tgname, pg_get_triggerdef(t.oid, true) || ';'
FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid JOIN esquemas s ON s.oid = c.relnamespace
WHERE NOT t.tgisinternal
UNION ALL
-- 9. Seguridad: tablas con RLS activado
SELECT 9, 'rls', s.nspname || '.' || c.relname,
       'ALTER TABLE ' || s.nspname || '.' || c.relname || ' ENABLE ROW LEVEL SECURITY;'
       || CASE WHEN c.relforcerowsecurity THEN ' ALTER TABLE ' || s.nspname || '.' || c.relname || ' FORCE ROW LEVEL SECURITY;' ELSE '' END
FROM pg_class c JOIN esquemas s ON s.oid = c.relnamespace
WHERE c.relkind IN ('r', 'p') AND c.relrowsecurity
UNION ALL
-- 10. Seguridad: políticas RLS
SELECT 10, 'politica', pol.schemaname || '.' || pol.tablename || '.' || pol.policyname,
       'CREATE POLICY ' || quote_ident(pol.policyname) || ' ON ' || pol.schemaname || '.' || pol.tablename
       || ' AS ' || pol.permissive || ' FOR ' || pol.cmd || ' TO ' || array_to_string(pol.roles, ', ')
       || COALESCE(' USING (' || pol.qual || ')', '') || COALESCE(' WITH CHECK (' || pol.with_check || ')', '') || ';'
FROM pg_policies pol
WHERE pol.schemaname IN (SELECT nspname FROM esquemas)
UNION ALL
-- 11. Seguridad: permisos por rol sobre tablas y vistas
SELECT 11, 'permiso', g.table_schema || '.' || g.table_name || ' -> ' || g.grantee,
       'GRANT ' || string_agg(g.privilege_type, ', ' ORDER BY g.privilege_type) || ' ON ' || g.table_schema || '.' || g.table_name || ' TO ' || g.grantee || ';'
FROM information_schema.role_table_grants g
WHERE g.table_schema IN (SELECT nspname FROM esquemas)
GROUP BY g.table_schema, g.table_name, g.grantee
UNION ALL
-- 12. Tamaño aproximado de cada tabla (filas estimadas, para planificar la copia de datos)
SELECT 12, 'tamano', s.nspname || '.' || c.relname,
       '-- filas estimadas: ' || c.reltuples::bigint || ' | tamano: ' || pg_size_pretty(pg_total_relation_size(c.oid))
FROM pg_class c JOIN esquemas s ON s.oid = c.relnamespace
WHERE c.relkind IN ('r', 'p')
UNION ALL
-- 13. Storage: buckets
SELECT 13, 'bucket', b.id,
       '-- bucket ' || b.name || ' | publico: ' || b.public::text
       || ' | limite por archivo: ' || COALESCE(b.file_size_limit::text, 'sin limite')
       || ' | tipos permitidos: ' || COALESCE(array_to_string(b.allowed_mime_types, ', '), 'todos')
FROM storage.buckets b
UNION ALL
-- 14. Storage: archivos por bucket (cantidad y tamaño total)
SELECT 14, 'bucket_contenido', o.bucket_id,
       '-- archivos: ' || COUNT(*) || ' | tamano total: '
       || pg_size_pretty(COALESCE(SUM((o.metadata ->> 'size')::bigint), 0))
FROM storage.objects o
GROUP BY o.bucket_id
UNION ALL
-- 15. Storage: políticas de acceso a los archivos
SELECT 15, 'politica_storage', pol.tablename || '.' || pol.policyname,
       'CREATE POLICY ' || quote_ident(pol.policyname) || ' ON ' || pol.schemaname || '.' || pol.tablename
       || ' AS ' || pol.permissive || ' FOR ' || pol.cmd || ' TO ' || array_to_string(pol.roles, ', ')
       || COALESCE(' USING (' || pol.qual || ')', '') || COALESCE(' WITH CHECK (' || pol.with_check || ')', '') || ';'
FROM pg_policies pol
WHERE pol.schemaname = 'storage'
UNION ALL
-- 16. Auth: cuántos usuarios hay y con qué proveedor de login (email, google...)
SELECT 16, 'auth_proveedor', i.provider,
       '-- usuarios: ' || COUNT(DISTINCT i.user_id)
FROM auth.identities i
GROUP BY i.provider
UNION ALL
SELECT 16, 'auth_total', 'auth.users', '-- usuarios totales: ' || COUNT(*) FROM auth.users
UNION ALL
-- 17. Realtime: tablas que emiten cambios en vivo
SELECT 17, 'realtime', pt.schemaname || '.' || pt.tablename, '-- publicacion: ' || pt.pubname
FROM pg_publication_tables pt
WHERE pt.pubname LIKE 'supabase_realtime%'
ORDER BY 1, 3;
